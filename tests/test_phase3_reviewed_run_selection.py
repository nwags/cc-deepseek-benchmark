def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def parse_dashboard_module(path: Path) -> dict:
    source = path.read_text(encoding="utf-8")
    match = re.fullmatch(
        r"// Generated by scripts/generate_phase3_reviewed_run_selection\.py\. Do not edit\.\n"
        r"const reviewedRunSelection = JSON\.parse\((.+)\);\n"
        r"export default reviewedRunSelection;\n",
        source,
    )
    assert match
    return json.loads(json.loads(match.group(1)))


