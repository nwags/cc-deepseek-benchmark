def test_temporary_file_is_cleaned_after_atomic_replace_failure(tmp_path: Path, monkeypatch) -> None:
    output = tmp_path / "selection.json"
    dashboard = tmp_path / "selection.ts"
    def fail_replace(_source: Path, _destination: Path) -> None:
        raise OSError("forced replace failure")
    monkeypatch.setattr(generator.os, "replace", fail_replace)
    with pytest.raises(OSError, match="forced replace failure"):
        generator.write_snapshot(generator.default_input_paths(), output, dashboard)
    assert not list(tmp_path.glob(".*.tmp"))


