def write_mutated_table(
    source: Path,
    destination: Path,
    delimiter: str,
    mutate,
) -> None:
    with source.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle, delimiter=delimiter)
        rows = list(reader)
        fieldnames = reader.fieldnames
    assert fieldnames
    mutate(rows)
    with destination.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, delimiter=delimiter, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def test_missing_and_unexpected_core_arms_fail(tmp_path: Path) -> None:
    source = generator.default_input_paths()["trial_cost_coverage"]
    missing = tmp_path / "missing.tsv"
    write_mutated_table(
        source,
        missing,
        "\t",
        lambda rows: rows.__setitem__(slice(None), [
            row for row in rows if row["arm_id"] != "router-gpt-5.5"
        ]),
    )
    paths = generator.default_input_paths()
    paths["trial_cost_coverage"] = missing
    with pytest.raises(ValueError, match="900 trials|15 arms"):
        generator.generate_snapshot(paths)

    unexpected = tmp_path / "unexpected.tsv"
    def replace_arm(rows: list[dict[str, str]]) -> None:
        for row in rows:
            if row["arm_id"] == "router-gpt-5.5":
                row["arm_id"] = "router-unexpected"
                row["run_label"] = row["run_label"].replace("router-gpt-5.5/", "router-unexpected/")
    write_mutated_table(source, unexpected, "\t", replace_arm)
    paths["trial_cost_coverage"] = unexpected
    with pytest.raises(ValueError, match="membership differs"):
        generator.generate_snapshot(paths)


