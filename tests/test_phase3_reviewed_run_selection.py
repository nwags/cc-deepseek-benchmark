def test_duplicate_independent_run_label_fails(tmp_path: Path) -> None:
    paths = generator.default_input_paths()
    run_review = tmp_path / "run_review.csv"
    def duplicate_label(rows: list[dict[str, str]]) -> None:
        selected = [row for row in rows if row["selected"] == "True"]
        selected[1]["run_label"] = selected[0]["run_label"]
    write_mutated_table(paths["review_run_rows"], run_review, ",", duplicate_label)

    manifest = json.loads(paths["review_manifest"].read_text(encoding="utf-8"))
    manifest["outputs"]["run_review.csv"]["sha256"] = sha256(run_review)
    manifest_path = tmp_path / "review_manifest.json"
    manifest_path.write_text(json.dumps(manifest), encoding="utf-8")
    paths["review_run_rows"] = run_review
    paths["review_manifest"] = manifest_path
    with pytest.raises(ValueError, match="duplicate arm IDs or run labels"):
        generator.generate_snapshot(paths)


